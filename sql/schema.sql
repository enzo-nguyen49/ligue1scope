-- Rejouable : CREATE ... IF NOT EXISTS + ALTER ... ADD COLUMN IF NOT EXISTS
-- pour migrer une base creee avec la version 1.x du projet.

CREATE TABLE IF NOT EXISTS season (
    season_id VARCHAR(9) PRIMARY KEY
        CHECK (season_id ~ '^[0-9]{4}-[0-9]{4}$')
);

CREATE TABLE IF NOT EXISTS team (
    team_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_name TEXT NOT NULL UNIQUE CHECK (length(trim(team_name)) > 0)
);

CREATE TABLE IF NOT EXISTS football_match (
    match_id TEXT PRIMARY KEY CHECK (length(trim(match_id)) > 0),
    season_id VARCHAR(9) NOT NULL REFERENCES season(season_id),
    match_date DATE NOT NULL,
    kickoff_time TIME,
    home_team_id INTEGER NOT NULL REFERENCES team(team_id),
    away_team_id INTEGER NOT NULL REFERENCES team(team_id),
    home_goals SMALLINT NOT NULL CHECK (home_goals BETWEEN 0 AND 15),
    away_goals SMALLINT NOT NULL CHECK (away_goals BETWEEN 0 AND 15),
    result CHAR(1) NOT NULL CHECK (result IN ('H', 'D', 'A')),
    home_elo DOUBLE PRECISION NOT NULL,
    away_elo DOUBLE PRECISION NOT NULL,
    elo_diff DOUBLE PRECISION NOT NULL,
    kickoff_time_missing BOOLEAN NOT NULL DEFAULT FALSE,
    data_quality_status TEXT NOT NULL DEFAULT 'complete',
    CHECK (home_team_id <> away_team_id),
    CHECK (
        (home_goals > away_goals AND result = 'H')
        OR (home_goals = away_goals AND result = 'D')
        OR (home_goals < away_goals AND result = 'A')
    ),
    CHECK (abs(elo_diff - (home_elo - away_elo)) < 0.11),
    UNIQUE (season_id, match_date, home_team_id, away_team_id)
);

