CREATE VIEW v_match_analysis AS
SELECT
    m.match_id,
    m.season_id AS season,
    m.match_date,
    m.kickoff_time,
    home.team_name AS home_team,
    away.team_name AS away_team,
    m.home_goals,
    m.away_goals,
    m.home_goals + m.away_goals AS total_goals,
    m.result,
    m.home_elo,
    m.away_elo,
    m.elo_diff,
    m.elo_home_win_expectancy,
    m.elo_favorite,
    (m.elo_favorite = m.result) AS elo_favorite_won,
    m.elo_warmup,
    m.odds_home_avg,
    m.odds_draw_avg,
    m.odds_away_avg,
    m.market_prob_home,
    m.market_prob_draw,
    m.market_prob_away,
    m.market_favorite,
    (m.market_favorite = m.result) AS market_favorite_won,
    m.odds_valid,
    w.weather_temp_c,
    w.weather_precip_mm,
    w.weather_wind_kph,
    w.weather_granularity,
    m.kickoff_time_missing,
    w.weather_missing,
    m.data_quality_status,
    CASE
        WHEN m.elo_diff < -200 THEN '< -200'
        WHEN m.elo_diff < -100 THEN '-200 à -100'
        WHEN m.elo_diff < 0 THEN '-100 à 0'
        WHEN m.elo_diff < 100 THEN '0 à 100'
        WHEN m.elo_diff < 200 THEN '100 à 200'
        ELSE '≥ 200'
    END AS elo_band,
    CASE
        WHEN w.weather_temp_c IS NULL THEN 'Non renseignée'
        WHEN w.weather_temp_c < 5 THEN '< 5 °C'
        WHEN w.weather_temp_c < 10 THEN '5 à < 10 °C'
        WHEN w.weather_temp_c < 15 THEN '10 à < 15 °C'
        WHEN w.weather_temp_c < 20 THEN '15 à < 20 °C'
        WHEN w.weather_temp_c < 25 THEN '20 à < 25 °C'
        ELSE '≥ 25 °C'
    END AS temperature_class,
    CASE
        WHEN w.weather_precip_mm IS NULL THEN 'Non renseignée'
        WHEN w.weather_precip_mm = 0 THEN '0 mm'
        WHEN w.weather_precip_mm <= 1 THEN '> 0 à 1 mm'
        WHEN w.weather_precip_mm <= 5 THEN '> 1 à 5 mm'
        ELSE '> 5 mm'
    END AS precipitation_class,
    m.source_file,
    m.raw_sha256,
    m.last_run_id
FROM football_match AS m
JOIN team AS home ON home.team_id = m.home_team_id
JOIN team AS away ON away.team_id = m.away_team_id
LEFT JOIN match_weather AS w ON w.match_id = m.match_id;

CREATE VIEW v_kpi_favori_par_saison AS
SELECT
    season,
    COUNT(*) AS matches,
    ROUND(AVG(elo_favorite_won::int)::numeric, 4) AS elo_favorite_win_rate,
    ROUND(AVG(market_favorite_won::int)::numeric, 4) AS market_favorite_win_rate,
    ROUND(AVG((elo_favorite = market_favorite)::int)::numeric, 4) AS elo_market_agreement_rate,
    ROUND(AVG((result = 'H')::int)::numeric, 4) AS home_win_rate,
    ROUND(AVG((result = 'D')::int)::numeric, 4) AS draw_rate
FROM v_match_analysis
WHERE NOT elo_warmup
GROUP BY season;

CREATE VIEW v_kpi_tranche_elo AS
SELECT
    elo_band,
    COUNT(*) AS matches,
    ROUND(AVG((result = 'H')::int)::numeric, 4) AS home_win_rate,
    ROUND(AVG((result = 'D')::int)::numeric, 4) AS draw_rate,
    ROUND(AVG((result = 'A')::int)::numeric, 4) AS away_win_rate,
    ROUND(AVG(total_goals)::numeric, 3) AS avg_goals,
    ROUND(AVG(home_goals - away_goals)::numeric, 3) AS avg_goal_diff
FROM v_match_analysis
WHERE NOT elo_warmup
GROUP BY elo_band;

CREATE VIEW v_kpi_meteo_temperature AS
SELECT
    temperature_class,
    COUNT(*) AS matches,
    ROUND(AVG((result = 'H')::int)::numeric, 4) AS home_win_rate,
    ROUND(AVG((result = 'D')::int)::numeric, 4) AS draw_rate,
    ROUND(AVG(total_goals)::numeric, 3) AS avg_goals
FROM v_match_analysis
WHERE NOT elo_warmup
GROUP BY temperature_class;

CREATE VIEW v_kpi_meteo_precipitations AS
SELECT
    precipitation_class,
    COUNT(*) AS matches,
    ROUND(AVG((result = 'H')::int)::numeric, 4) AS home_win_rate,
    ROUND(AVG((result = 'D')::int)::numeric, 4) AS draw_rate,
    ROUND(AVG(total_goals)::numeric, 3) AS avg_goals
FROM v_match_analysis
WHERE NOT elo_warmup
GROUP BY precipitation_class;
